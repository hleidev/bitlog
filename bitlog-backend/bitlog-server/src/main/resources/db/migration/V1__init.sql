(
    id               bigint        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    article_id       bigint        NOT NULL,
    user_id          bigint        NOT NULL,
    root_id          bigint,
    parent_id        bigint,
    reply_to_user_id bigint,
    content          varchar(1000) NOT NULL,
    status           smallint      NOT NULL DEFAULT 1,
    deleted          smallint      NOT NULL DEFAULT 0,
    create_time      timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time      timestamptz   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    CONSTRAINT fk_comment_article FOREIGN KEY (article_id) REFERENCES article (id),
    CONSTRAINT fk_comment_user FOREIGN KEY (user_id) REFERENCES user_account (id),
    CONSTRAINT fk_comment_root FOREIGN KEY (root_id) REFERENCES comment (id),
    CONSTRAINT fk_comment_parent FOREIGN KEY (parent_id) REFERENCES comment (id),
    CONSTRAINT fk_comment_reply_to_user FOREIGN KEY (reply_to_user_id) REFERENCES user_account (id)
