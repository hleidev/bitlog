-- update_time 由触发器统一维护，应用层无需赋值
CREATE FUNCTION touch_update_time() RETURNS trigger AS $$
BEGIN
    NEW.update_time = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;


-- ---------- 用户账号表 ----------
CREATE TABLE user_account
(
    id          bigint      NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    username    varchar(16) NOT NULL,
    password    varchar(60),
    email       varchar(128),
    status      smallint    NOT NULL DEFAULT 1,
    user_role   smallint    NOT NULL DEFAULT 0,
    deleted     smallint    NOT NULL DEFAULT 0,
    create_time timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    update_time timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (id)
);

COMMENT ON TABLE user_account IS '用户账号表';
COMMENT ON COLUMN user_account.id IS '主键ID';
COMMENT ON COLUMN user_account.username IS '用户名，唯一且可修改的公开展示名';
COMMENT ON COLUMN user_account.password IS '密码，BCrypt 加密；第三方登录用户为空';
COMMENT ON COLUMN user_account.email IS '登录邮箱，统一小写存储';
COMMENT ON COLUMN user_account.status IS '账号状态：0-禁用，1-启用';
COMMENT ON COLUMN user_account.user_role IS '角色：0-普通用户，1-管理员';
COMMENT ON COLUMN user_account.deleted IS '删除标记：0-正常，1-已删除';

-- 注销记录退出唯一性判定，原始 username/email 得以原样保留供审计
CREATE UNIQUE INDEX uk_user_account_username ON user_account (username) WHERE deleted = 0;
CREATE UNIQUE INDEX uk_user_account_email ON user_account (email) WHERE deleted = 0;

CREATE TRIGGER trg_user_account_touch
    BEFORE UPDATE ON user_account
    FOR EACH ROW EXECUTE FUNCTION touch_update_time();


